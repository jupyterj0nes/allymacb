"""Measures what the hours of clean machines look like and writes src/hours.rs.

    python scripts/measure_hours.py <out.rs> <kind>=<timeline.csv>[|<exclude regex>] ...

<kind> is ntfs, usn or unix; the CSV is an allymacb timeline of a clean
machine (nothing planted), the exclude regex drops the records of the
collection itself (the folder the collection scripts wrote into). From the
rows it rebuilds every record (one per `meta` for `mft` and Unix sources, one
per row for `usn`), the hour it last changed (the `$SI` change time, then
modification, then creation; the record's time for a journal record) and the
rules that fired on it (the `rule <id>` clauses of `hunt_why`), and counts,
hour by hour, how many records changed and how many of them carry each rule.
Those hours are the null of the hour test in src/context.rs: an hour of a
case is judged by how many clean hours reach the share of records with the
same rule.
"""
import collections
import csv
import datetime
import re
import sys

RULE = re.compile(r'rule (\w+) \(')
# the timestomp signature is measured as one pattern, as src/anomaly.rs scores it
PAIR = 'si_before_fn+si_subsec_zero'
KINDS = {'ntfs': ('mft',), 'usn': ('usn',), 'unix': ('bodyfile', 'ext4', 'xfs', 'fs')}


def hours_of(path, sources, exclude):
    change = {}      # record -> (secs, letter rank)
    rules = {}       # record -> set of rule ids
    with open(path, encoding='utf-8', newline='') as f:
        for r in csv.DictReader(f):
            if r['source'] not in sources or '($FILE_NAME' in r['file_name']:
                continue
            if exclude and exclude.search(r['file_name']):
                continue
            key = (r['source'], r['meta']) if r['source'] != 'usn' else (r['source'], r['meta'], r['time_created'], r['file_name'])
            t = r['type']
            rank = 0 if 'c' in t else 1 if 'm' in t else 2 if 'b' in t else 3
            secs = int(datetime.datetime.strptime(r['time_created'][:19], '%Y-%m-%dT%H:%M:%S').replace(tzinfo=datetime.timezone.utc).timestamp())
            if r['source'] == 'usn':
                rank = 0
            if key not in change or rank < change[key][1]:
                change[key] = (secs, rank)
            if r['hunt_why']:
                found = set(RULE.findall(r['hunt_why']))
                if {'si_before_fn', 'si_subsec_zero'} <= found:
                    found.add(PAIR)
                rules.setdefault(key, set()).update(found)
    per_hour = collections.defaultdict(lambda: [0, collections.Counter()])
    for key, (secs, rank) in change.items():
        if rank == 3:
            continue
        h = secs // 3600
        per_hour[h][0] += 1
        for rule in rules.get(key, ()):
            per_hour[h][1][rule] += 1
    return per_hour


def main():
    out = sys.argv[1]
    tables = collections.defaultdict(list)
    sources_used = []
    for arg in sys.argv[2:]:
        kind, rest = arg.split('=', 1)
        path, excl = rest.rsplit('|', 1) if '|' in rest else (rest, '')
        exclude = re.compile(excl, re.I) if excl else None
        per_hour = hours_of(path, KINDS[kind], exclude)
        for h in sorted(per_hour):
            changed, hits = per_hour[h]
            label = datetime.datetime.fromtimestamp(h * 3600, datetime.timezone.utc).strftime('%Y-%m-%dT%H')
            tables[kind].append((label, changed, sorted(hits.items())))
        sources_used.append(f'{kind}: {path} ({len(per_hour)} hours)')
        print(f'{kind}: {len(per_hour)} hours from {path}')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('//! The hours of clean machines: the null of the hour test in [`crate::context`].\n')
        f.write('//! Generated by `scripts/measure_hours.py`; do not edit by hand.\n//!\n')
        for s in sources_used:
            f.write(f'//! * {s}\n')
        f.write('\n/// One hour of a clean volume: how many records changed in it and how\n')
        f.write('/// many of them carry each rule (rules absent from `hits` fired on none).\n')
        f.write('pub struct CleanHour {\n    /// `2026-11-03T10`, UTC.\n    pub label: &\'static str,\n    pub changed: u32,\n    pub hits: &\'static [(&\'static str, u32)],\n}\n')
        for kind, name in (('ntfs', 'NTFS'), ('usn', 'USN'), ('unix', 'UNIX')):
            rows = tables.get(kind, [])
            f.write(f'\n/// Clean hours of {kind} records: {len(rows)}.\n')
            f.write(f'pub const {name}: &[CleanHour] = &[\n')
            for label, changed, hits in rows:
                h = ', '.join(f'("{r}", {n})' for r, n in hits)
                f.write(f'    CleanHour {{ label: "{label}", changed: {changed}, hits: &[{h}] }},\n')
            f.write('];\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
